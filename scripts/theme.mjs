// Generates assets/theme.css: a full Material Design 3 color scheme (light + dark)
// from one seed color, using Google's material-color-utilities (tonal spot, the default M3 variant).
// material-color-utilities 0.4.0 ships extensionless ESM imports that plain Node cannot
// resolve, so `npm run theme` bundles this script with esbuild first, then runs it.
// Usage: npm run theme            (default seed)
//        npm run theme -- #2a4bc4 (custom seed)
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors, Contrast,
} from '@material/material-color-utilities';

const SEED = process.argv[2] || '#2a4bc4';
const OUT = resolve('assets/theme.css'); // npm scripts run from the package root

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'inverseSurface', 'inverseOnSurface', 'surfaceTint',
  'outline', 'outlineVariant', 'shadow', 'scrim',
];

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const mdc = new MaterialDynamicColors();
const source = Hct.fromInt(argbFromHex(SEED));

function scheme(isDark) {
  const s = new SchemeTonalSpot(source, isDark, 0);
  const out = {};
  for (const role of ROLES) out[role] = mdc[role]().getArgb(s);
  return out;
}

const light = scheme(false);
const dark = scheme(true);
const block = (c, indent = '  ') =>
  ROLES.map((r) => `${indent}--md-sys-color-${kebab(r)}: ${hexFromArgb(c[r])};`).join('\n');

const css = `/* Generated by scripts/theme.mjs from seed ${SEED} (M3 tonal spot, the Material You default). Do not edit by hand: run \`npm run theme\`. */
:root {
  color-scheme: light;
${block(light)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block(dark, '    ')}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${block(light)}
}
:root[data-theme="dark"] {
  color-scheme: dark;
${block(dark)}
}
`;
writeFileSync(OUT, css);
console.log(`Wrote ${OUT} (seed ${SEED})`);

// Report WCAG contrast for the key text/background pairs.
const lum = (argb) => Hct.fromInt(argb).tone;
const pairs = [
  ['onSurface', 'surface'], ['onSurfaceVariant', 'surface'], ['onSurfaceVariant', 'surfaceContainerLow'],
  ['onSurface', 'surfaceContainerLow'], ['onSurface', 'surfaceContainer'], ['primary', 'surface'],
  ['primary', 'surfaceContainerLow'], ['onPrimary', 'primary'], ['onPrimaryContainer', 'primaryContainer'],
  ['onSecondaryContainer', 'secondaryContainer'], ['onTertiaryContainer', 'tertiaryContainer'],
];
for (const [name, c] of [['light', light], ['dark', dark]]) {
  const rows = pairs.map(([fg, bg]) => `${fg}/${bg} ${Contrast.ratioOfTones(lum(c[fg]), lum(c[bg])).toFixed(2)}`);
  console.log(`${name}: ${rows.join(', ')}`);
}
